// Code-Block in Format_Dev_Payload (Kommentar + Array), erzeugt aus PLATFORM_FACTS.
function factsCode(facts, comment) {
  return [comment, "const PLATFORM_FACTS = [", ...facts.map(f => "  " + JSON.stringify(f) + ","), "];", ""].join('\n');
}
