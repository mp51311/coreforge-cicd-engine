// PLATFORM_FACTS aus einem Format_Dev_Payload-Code lesen: Code ausführen (Stub-Eingabe) und das Ausgabefeld nehmen.
async function factsFromFdpCode(code) {
  const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
  const fn = new AsyncFunction('$', '$input', '$json', 'Buffer', code);
  const out = await fn(() => { throw new Error('$() im Stub nicht verfügbar'); }, { all: () => [] }, { output: '{"project_name":"Drift Probe"}' }, Buffer);
  return out[0].json.platform_facts;
}
// Fakten-Block aus dem PO-Prompt lesen: Zeilen "- ..." direkt nach PO_FACTS_INTRO bis zur ersten Leerzeile.
function factsFromPoPrompt(prompt) {
  const i = prompt.indexOf(PO_FACTS_INTRO + '\n');
  if (i === -1) return null;
  const lines = prompt.slice(i + PO_FACTS_INTRO.length + 1).split('\n');
  const out = [];
  for (const l of lines) { if (!l.startsWith('- ')) break; out.push(l.slice(2)); }
  return out;
}
// Drift-Prüfung: beide Stellen müssen exakt PLATFORM_FACTS (Reihenfolge, Bytes, Anzahl) enthalten.
async function checkDrift(fdpCode, poPrompt) {
  const problems = [];
  let fdp;
  try { fdp = await factsFromFdpCode(fdpCode); } catch (e) { problems.push('Format_Dev_Payload nicht ausführbar: ' + e.message); }
  const po = factsFromPoPrompt(poPrompt);
  if (!po) problems.push('PO-Prompt: Fakten-Block (Einleitungssatz) fehlt');
  const cmp = (label, arr) => {
    if (!Array.isArray(arr)) { problems.push(label + ': keine Fakten gelesen'); return; }
    if (arr.length !== PLATFORM_FACTS.length) problems.push(`${label}: ${arr.length} Fakten statt ${PLATFORM_FACTS.length}`);
    PLATFORM_FACTS.forEach((f, k) => { if (arr[k] !== f) problems.push(`${label}: Fakt ${k + 1} weicht ab`); });
  };
  if (fdp !== undefined) cmp('Format_Dev_Payload', fdp);
  if (po) cmp('PO-Prompt', po);
  if (Array.isArray(fdp) && po && JSON.stringify(fdp) !== JSON.stringify(po)) problems.push('Format_Dev_Payload und PO-Prompt unterschiedlich');
  return problems;
}

